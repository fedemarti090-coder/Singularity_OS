inline const uint8_t* glyph_for(char c) {
    uint8_t idx = static_cast<uint8_t>(c);
    if (idx >= NUM_GLYPHS) {
        idx = '?';
    }
    return kGlyphs[idx];
}

inline void draw_char(uint32_t x0, uint32_t y0, char c, uint32_t fg_color, bool has_bg = false, uint32_t bg_color = 0) {
    uint32_t* back = Framebuffer::backbuffer();
    uint32_t pitch_pixels = Framebuffer::pitch() / sizeof(uint32_t);
    uint32_t fb_w = Framebuffer::width();
    uint32_t fb_h = Framebuffer::height();

    if (back == nullptr || pitch_pixels == 0) {
        return;
    }

    const uint8_t* g = glyph_for(c);

    for (uint32_t dy = 0; dy < GLYPH_H; ++dy) {
        uint32_t py = y0 + dy;
        if (py >= fb_h) {
            break;
        }
        uint8_t bits = g[dy];
        uint32_t* dst_row = back + static_cast<size_t>(py) * pitch_pixels;

        for (uint32_t dx = 0; dx < GLYPH_W; ++dx) {
            uint32_t px = x0 + dx;
            if (px >= fb_w) {
                break;
            }
            bool lit = (bits & (0x80u >> dx)) != 0;
            if (lit) {
                dst_row[px] = fg_color;
            } else if (has_bg) {
                dst_row[px] = bg_color;
            }
        }
    }
}

inline void draw_text(uint32_t x0, uint32_t y0, const char* text, uint32_t fg_color, bool has_bg = false, uint32_t bg_color = 0, uint32_t spacing = 0) {
    if (text == nullptr) {
        return;
    }

    uint32_t cursor_x = x0;
    uint32_t cursor_y = y0;
    uint32_t fb_w = Framebuffer::width();

    for (size_t i = 0; text[i] != '\0'; ++i) {
        char c = text[i];
        if (c == '\n') {
            cursor_x = x0;
            cursor_y += GLYPH_H + spacing;
            continue;
        }
        if (cursor_x + GLYPH_W > fb_w) {
            cursor_x = x0;
            cursor_y += GLYPH_H + spacing;
        }
        draw_char(cursor_x, cursor_y, c, fg_color, has_bg, bg_color);
        cursor_x += GLYPH_W + spacing;
    }
}

